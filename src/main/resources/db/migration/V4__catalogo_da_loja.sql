-- Catálogo da loja no formato que o front usa (contrato Product do commerce-web):
-- produto com slug, linha/versão, gênero, concentração, status e selo; preço e estoque
-- passam a ser da VARIANTE (frasco ou decant, cada uma com SKU próprio).
-- products.price/stock ficam por enquanto para o código antigo (carrinho, pedido, admin) até o B5/B6.

ALTER TABLE categories ADD COLUMN slug VARCHAR(60) UNIQUE;

ALTER TABLE products ALTER COLUMN description TYPE TEXT;
ALTER TABLE products ADD COLUMN slug          VARCHAR(160) UNIQUE;
ALTER TABLE products ADD COLUMN line          VARCHAR(120);
ALTER TABLE products ADD COLUMN subtitle      VARCHAR(120);
ALTER TABLE products ADD COLUMN gender        VARCHAR(20);
ALTER TABLE products ADD COLUMN concentration VARCHAR(40);
-- rascunho | publicado (só publicado aparece na loja)
ALTER TABLE products ADD COLUMN status        VARCHAR(20) NOT NULL DEFAULT 'rascunho';
ALTER TABLE products ADD COLUMN badge         VARCHAR(40);
-- Unidades vendidas: somado quando o pagamento é confirmado (B6). Ordena "Mais vendidos".
ALTER TABLE products ADD COLUMN sold_count    INTEGER NOT NULL DEFAULT 0;

CREATE TABLE product_variants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT         NOT NULL REFERENCES products (id),
    sku        VARCHAR(80)    NOT NULL UNIQUE,
    kind       VARCHAR(10)    NOT NULL, -- frasco | decant
    volume_ml  INTEGER,
    price      NUMERIC(10, 2) NOT NULL,
    stock      INTEGER        NOT NULL DEFAULT 0,
    position   INTEGER        NOT NULL DEFAULT 0
);
CREATE INDEX idx_product_variants_product ON product_variants (product_id);

-- Fotos na ordem da galeria (a primeira é a principal).
CREATE TABLE product_images (
    product_id BIGINT       NOT NULL REFERENCES products (id),
    position   INTEGER      NOT NULL,
    path       VARCHAR(255) NOT NULL,
    PRIMARY KEY (product_id, position)
);

CREATE TABLE product_families (
    product_id BIGINT      NOT NULL REFERENCES products (id),
    position   INTEGER     NOT NULL,
    family     VARCHAR(40) NOT NULL,
    PRIMARY KEY (product_id, position)
);

CREATE TABLE product_occasions (
    product_id BIGINT      NOT NULL REFERENCES products (id),
    position   INTEGER     NOT NULL,
    occasion   VARCHAR(10) NOT NULL, -- dia | noite
    PRIMARY KEY (product_id, position)
);

-- Pirâmide olfativa: camada (top | heart | base) e a nota, na ordem de exibição.
CREATE TABLE product_notes (
    product_id BIGINT      NOT NULL REFERENCES products (id),
    position   INTEGER     NOT NULL,
    layer      VARCHAR(10) NOT NULL,
    note       VARCHAR(60) NOT NULL,
    PRIMARY KEY (product_id, position)
);

-- Só kit: o que vem na caixa.
CREATE TABLE product_kit_items (
    product_id BIGINT       NOT NULL REFERENCES products (id),
    position   INTEGER      NOT NULL,
    item       VARCHAR(160) NOT NULL,
    PRIMARY KEY (product_id, position)
);
