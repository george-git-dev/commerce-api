-- Esquema inicial da commerce-api (31/10/2026): o mesmo que o Hibernate gerava com
-- ddl-auto=update, agora versionado. Daqui em diante o banco só muda por migração
-- nova (V2, V3...); migração que já rodou NUNCA é editada.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id VARCHAR(255) UNIQUE,
    cpf         VARCHAR(255) UNIQUE,
    name        VARCHAR(255),
    email       VARCHAR(255) NOT NULL UNIQUE,
    active      BOOLEAN
);

CREATE TABLE addresses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street          VARCHAR(255),
    number          VARCHAR(255),
    complement      VARCHAR(255),
    neighborhood    VARCHAR(255),
    city            VARCHAR(255),
    state           VARCHAR(255),
    zip_code        VARCHAR(255),
    primary_address BOOLEAN,
    user_id         BIGINT REFERENCES users (id)
);
CREATE INDEX idx_addresses_user ON addresses (user_id);

CREATE TABLE categories (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255),
    active BOOLEAN
);

CREATE TABLE brands (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    active BOOLEAN      NOT NULL
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    description VARCHAR(255),
    price       NUMERIC(38, 2),
    stock       INTEGER,
    active      BOOLEAN,
    category_id BIGINT REFERENCES categories (id),
    brand_id    BIGINT REFERENCES brands (id),
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6)
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_brand ON products (brand_id);

CREATE TABLE product_attributes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255),
    attribute_value VARCHAR(255),
    product_id      BIGINT REFERENCES products (id)
);
CREATE INDEX idx_product_attributes_product ON product_attributes (product_id);

CREATE TABLE promotions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255),
    description    VARCHAR(255),
    active         BOOLEAN,
    discount_type  VARCHAR(255),
    discount_value NUMERIC(38, 2),
    start_at       TIMESTAMP(6),
    end_at         TIMESTAMP(6)
);

CREATE TABLE product_promotions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT REFERENCES products (id),
    promotion_id BIGINT REFERENCES promotions (id)
);
CREATE INDEX idx_product_promotions_product ON product_promotions (product_id);
CREATE INDEX idx_product_promotions_promotion ON product_promotions (promotion_id);

CREATE TABLE carts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT UNIQUE REFERENCES users (id),
    coupon_code VARCHAR(255)
);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity   INTEGER,
    cart_id    BIGINT REFERENCES carts (id),
    product_id BIGINT REFERENCES products (id),
    version    BIGINT
);
CREATE INDEX idx_cart_items_cart ON cart_items (cart_id);
CREATE INDEX idx_cart_items_product ON cart_items (product_id);

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT REFERENCES users (id),
    address_id       BIGINT REFERENCES addresses (id),
    total            NUMERIC(38, 2),
    discount_applied NUMERIC(38, 2),
    notes            VARCHAR(255),
    coupon_code      VARCHAR(255),
    sale_channel     VARCHAR(255),
    status           VARCHAR(255),
    created_at       TIMESTAMP(6)
);
CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_orders_address ON orders (address_id);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT REFERENCES orders (id),
    product_name  VARCHAR(255),
    product_price NUMERIC(38, 2),
    quantity      INTEGER,
    subtotal      NUMERIC(38, 2),
    category_name VARCHAR(255),
    brand_name    VARCHAR(255)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT UNIQUE REFERENCES orders (id),
    amount     NUMERIC(38, 2),
    method     VARCHAR(255),
    status     VARCHAR(255),
    created_at TIMESTAMP(6)
);

CREATE TABLE affiliates (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT UNIQUE REFERENCES users (id),
    coupon_code           VARCHAR(255)   NOT NULL UNIQUE,
    active                BOOLEAN        NOT NULL,
    commission_percentage NUMERIC(38, 2) NOT NULL,
    discount_type         VARCHAR(255),
    discount_value        NUMERIC(38, 2) NOT NULL,
    expires_at            TIMESTAMP(6)   NOT NULL
);

CREATE TABLE affiliate_sales (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    affiliate_id      BIGINT REFERENCES affiliates (id),
    order_id          BIGINT REFERENCES orders (id),
    sale_amount       NUMERIC(38, 2),
    commission_amount NUMERIC(38, 2),
    paid              BOOLEAN,
    created_at        TIMESTAMP(6),
    paid_at           TIMESTAMP(6)
);
CREATE INDEX idx_affiliate_sales_affiliate ON affiliate_sales (affiliate_id);
CREATE INDEX idx_affiliate_sales_order ON affiliate_sales (order_id);

CREATE TABLE expenses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description  VARCHAR(255),
    amount       NUMERIC(38, 2),
    category     VARCHAR(255),
    expense_date DATE
);
